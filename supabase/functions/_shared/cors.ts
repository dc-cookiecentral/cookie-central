// Shared CORS headers + helpers. The browser invokes gmail-poll via
// supabase.functions.invoke (preflight OPTIONS), so the JSON functions answer
// CORS; the OAuth callback is a top-level navigation and doesn't need it.

export const corsHeaders = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers':
    'authorization, x-client-info, apikey, content-type',
  'Access-Control-Allow-Methods': 'POST, OPTIONS',
};

// Returns a 204 preflight response for OPTIONS, else null.
export function handleCors(req: Request): Response | null {
  if (req.method === 'OPTIONS') {
    return new Response('ok', { headers: corsHeaders });
  }
  return null;
}

export function json(body: unknown, status = 200): Response {
  return new Response(JSON.stringify(body), {
    status,
    headers: { ...corsHeaders, 'content-type': 'application/json' },
  });
}
